#!/usr/bin/env node
/**
 * Converts the supplied MuAPI model export ("MUAPI MODELS.json", 609 models) into
 * the normalized catalog the model platform consumes at runtime.
 *
 * WHY THIS EXISTS: the platform previously registered exactly three hand-written
 * model definitions, so the Video Studio fell back to a hardcoded array of
 * placeholder names that mapped to nothing. Hand-authoring 300+ definition files
 * is not viable, so the catalog is generated from the provider's own export and
 * turned into definitions by src/lib/models/videoModelFactory.js.
 *
 * Run: node scripts/generate-model-catalog.mjs
 */
import fs from "node:fs";

const SOURCE = "MUAPI MODELS.json";
const OUT = "src/lib/models/catalog/muapi-model-catalog.json";
const API_BASE = "https://api.muapi.ai";

// Categories that produce a deliverable Doolphin supports today. Deliberately
// excluded: "Text to Text", "Text to Audio", "Training", "Lora Support",
// "Image to 3D", "Text to 3D", "other" (not a studio deliverable), and
// "Audio to Video" (requires a user-supplied audio track, which no studio
// collects yet — enabling it would offer a model that must fail at submission).
const CATEGORY_TO_MODE = {
  "Text to Video": "text-to-video",
  "Image to Video": "image-to-video",
  "Video to Video": "video-extend",
  "Text to Image": "text-to-image",
  "Image to Image": "image-to-image",
};

const VIDEO_MODES = new Set(["text-to-video", "image-to-video", "video-extend"]);

function titleCase(name) {
  return String(name)
    .split(/[-_]/)
    .filter(Boolean)
    .map((part) => (/^\d/.test(part) || part.length <= 2 ? part.toUpperCase() : part[0].toUpperCase() + part.slice(1)))
    .join(" ")
    .replace(/\bTo\b/g, "to")
    .replace(/\bV(\d)/g, "v$1");
}

const raw = JSON.parse(fs.readFileSync(SOURCE, "utf8"));
const models = raw.models || [];

const entries = {};
const stats = { total: models.length, kept: 0, skippedCategory: 0, skippedNoPrice: 0, video: 0, image: 0 };

for (const model of models) {
  const mode = CATEGORY_TO_MODE[model.category];
  if (!mode) { stats.skippedCategory += 1; continue; }

  // A model with no published cost has no basis for the drift guard that protects
  // against under-charging, so it cannot be offered. Excluded rather than guessed.
  if (!(typeof model.cost === "number" && model.cost > 0)) { stats.skippedNoPrice += 1; continue; }

  const isVideo = VIDEO_MODES.has(mode);
  entries[model.name] = {
    providerModelId: model.name,
    displayName: titleCase(model.name),
    description: model.description || "",
    category: model.category,
    mode,
    family: model.family || null,
    groupOf: model.group_of || null,
    mediaType: isVideo ? "VIDEO" : "IMAGE",
    cost: model.cost,
    costCurrency: model.cost_currency || "USD",
    costStrategy: model.cost_strategy || null,
    dynamicPricing: Boolean(model.dynamic_pricing),
    endpoint: model.endpoint ? `${API_BASE}${model.endpoint}` : null,
    estimateEndpoint: model.estimate_endpoint ? `${API_BASE}${model.estimate_endpoint}` : null,
  };
  stats.kept += 1;
  if (isVideo) stats.video += 1; else stats.image += 1;
}

const payload = {
  revision: `2026-08-muapi-model-catalog-v1`,
  generatedFrom: SOURCE,
  generatedAt: new Date().toISOString().slice(0, 10),
  note: "Generated by scripts/generate-model-catalog.mjs from the provider's own model export. Costs are representative bases used for display and the drift guard; the billed figure always comes from the estimate-cost endpoint.",
  counts: { total: stats.kept, video: stats.video, image: stats.image },
  models: entries,
};

fs.writeFileSync(OUT, `${JSON.stringify(payload, null, 2)}\n`);
console.log(`source models        : ${stats.total}`);
console.log(`skipped (category)   : ${stats.skippedCategory}`);
console.log(`skipped (no price)   : ${stats.skippedNoPrice}`);
console.log(`WROTE ${OUT}`);
console.log(`  total kept : ${stats.kept}`);
console.log(`  video      : ${stats.video}`);
console.log(`  image      : ${stats.image}`);
