import fs from "fs";
import path from "path";
import crypto from "crypto";
import sharp from "sharp";
import { buildStorageKey } from "../src/lib/storage/storageKey.js";
import { R2StorageService } from "../src/lib/storage/r2StorageService.js";

const EXPLORE_DIR = path.resolve("./Explore Images");
const PUBLIC_EXPLORE_DIR = path.resolve("./public/explore/images");
const THUMBS_DIR = path.resolve("./public/explore/images/thumbs");
const MANIFEST_PATH = path.resolve("./src/lib/explore-images-data.js");

function toTitleCase(str) {
  return str
    .replace(/\.[^/.]+$/, "")
    .replace(/_/g, " ")
    .replace(/-/g, " ")
    .replace(/\b\w/g, (char) => char.toUpperCase());
}

function toStableId(filename) {
  return filename
    .replace(/\.[^/.]+$/, "")
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

async function prepare() {
  console.log("[EXPLORE_PREPARE] Starting Explore Images preparation pipeline...");

  if (!fs.existsSync(EXPLORE_DIR)) {
    console.error(`[EXPLORE_PREPARE] Source directory not found: ${EXPLORE_DIR}`);
    process.exit(1);
  }

  fs.mkdirSync(PUBLIC_EXPLORE_DIR, { recursive: true });
  fs.mkdirSync(THUMBS_DIR, { recursive: true });

  const files = fs.readdirSync(EXPLORE_DIR).filter((file) => !file.startsWith(".") && /\.(png|jpe?g|webp)$/i.test(file));
  files.sort();

  const manifestEntries = [];

  for (const filename of files) {
    const filePath = path.join(EXPLORE_DIR, filename);
    const buffer = fs.readFileSync(filePath);
    const checksumSha256 = crypto.createHash("sha256").update(buffer).digest("hex");
    const ext = path.extname(filename).toLowerCase() || ".png";
    const stableId = toStableId(filename);
    const title = toTitleCase(filename);

    const image = sharp(buffer);
    const metadata = await image.metadata();

    const width = metadata.width || 1024;
    const height = metadata.height || 1024;
    const aspectRatio = parseFloat((width / height).toFixed(3));
    const mimeType = metadata.format === "jpeg" ? "image/jpeg" : metadata.format === "webp" ? "image/webp" : "image/png";

    // Generate lightweight WebP thumbnail (~400px display width)
    const thumbFilename = `${stableId}.webp`;
    const thumbPath = path.join(THUMBS_DIR, thumbFilename);
    await sharp(buffer)
      .resize({ width: 450, withoutEnlargement: true })
      .webp({ quality: 80 })
      .toFile(thumbPath);

    // Also copy / store local display image in public/explore/images/ for local dev preview
    const localImagePath = path.join(PUBLIC_EXPLORE_DIR, `${stableId}${ext}`);
    if (!fs.existsSync(localImagePath)) {
      fs.copyFileSync(filePath, localImagePath);
    }

    const storageKey = buildStorageKey("curated", ["explore-images", `${checksumSha256}${ext}`], { DOOLPHIN_ENV: "production" });
    const activeStorageKey = buildStorageKey("curated", ["explore-images", `${checksumSha256}${ext}`]);

    // Perform R2 sync only if R2 is configured and in staging environment
    if (R2StorageService.isConfigured() && process.env.DOOLPHIN_ENV === "staging") {
      try {
        const check = await R2StorageService.checkObjectExists(activeStorageKey);
        if (!check.exists) {
          await R2StorageService.uploadFile({
            storageKey: activeStorageKey,
            buffer,
            contentType: mimeType,
          });
          console.log(`[EXPLORE_PREPARE] Uploaded ${filename} to R2 (${activeStorageKey})`);
        }
      } catch (err) {
        console.warn(`[EXPLORE_PREPARE] R2 upload skipped for ${filename}:`, err.message);
      }
    }

    manifestEntries.push({
      id: stableId,
      title,
      filename,
      storageKey,
      checksumSha256,
      mimeType,
      fileSizeBytes: buffer.length,
      width,
      height,
      aspectRatio,
      thumbUrl: `/explore/images/thumbs/${thumbFilename}`,
      localUrl: `/explore/images/${stableId}${ext}`,
    });
  }

  const manifestContent = `/**
 * Authoritative Curated Explore Images Manifest
 * Generated by scripts/prepare-explore-images.mjs
 */

export const EXPLORE_IMAGES = ${JSON.stringify(manifestEntries, null, 2)};

export function getExploreImageById(id) {
  if (!id) return null;
  return EXPLORE_IMAGES.find((item) => item.id === id) || null;
}
`;

  fs.writeFileSync(MANIFEST_PATH, manifestContent, "utf8");
  console.log(`[EXPLORE_PREPARE] Successfully processed ${manifestEntries.length} explore images.`);
  console.log(`[EXPLORE_PREPARE] Manifest written to ${MANIFEST_PATH}`);
}

prepare().catch((err) => {
  console.error("[EXPLORE_PREPARE] Failed:", err);
  process.exit(1);
});
